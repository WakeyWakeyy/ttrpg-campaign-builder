import { test, expect } from "@playwright/test";
import { testPool } from "./database";
import { planningCampaign, planningEditor as editor, recoverPlanning } from "./planning-draft-helpers";
test("Encounter and creatures retain complete sections across validation, related saves and repeated races", async ({ page, context }) => {
  const pool = testPool(), other = await context.newPage();
  try {
    await planningCampaign(page);
    await page.locator("#new-encounter-title").fill("Crossing");
    await page.getByRole("button", { name: "Create encounter", exact: true }).click();
    await expect(page).toHaveURL(/\/encounters\/[0-9a-f-]+$/);
    const id = page.url().split("/").pop()!;
    const main = editor(page, "#encounter-title"), add = editor(page, "#new-creature-name");
    await add.getByLabel("Name", { exact: true }).fill("Guard"); await add.getByLabel("XP per creature").fill("100");
    await add.getByRole("button", { name: "Add creature", exact: true }).click();
    await expect(add.getByRole("status").filter({ hasText: /^Creature created\./ })).toHaveText("Creature created. Other sections were not saved.");
    await expect(add.locator('input[name="expectedRevision"]')).toHaveValue("2");
    const creature = editor(page, '[id^="creature-name-"]');
    await main.getByLabel("Title", { exact: true }).fill("   ");
    await main.getByLabel("Preparation notes").fill("  LOCAL IDEA\nSecond line  ");
    await main.getByLabel("Party level").fill("3");
    await main.getByRole("button", { name: "Save encounter", exact: true }).click();
    await expect(main.getByRole("alert")).toContainText("Check the title");
    await expect(main.getByLabel("Title", { exact: true })).toHaveValue("   ");
    await expect(main.getByLabel("Preparation notes")).toHaveValue("  LOCAL IDEA\nSecond line  ");
    await main.getByLabel("Title", { exact: true }).fill("Local crossing");
    await add.getByLabel("Name", { exact: true }).fill("Pending creature");
    await add.getByLabel("XP per creature").fill("250"); await add.getByLabel("Quantity").fill("4");
    await creature.getByLabel("Quantity").fill("2");
    await creature.getByRole("button", { name: "Save creature", exact: true }).click();
    await expect(creature.getByRole("status").filter({ hasText: /^Creature saved\./ })).toHaveText("Creature saved. Other sections were not saved.");
    await expect(creature.locator('input[name="expectedRevision"]')).toHaveValue("3");
    await expect(main.getByLabel("Party level")).toHaveValue("3");
    await expect(main.getByLabel("Number of characters")).toHaveValue("4");
    await expect(main.locator('input[name="expectedRevision"]')).toHaveValue("2");
    await expect(add.getByLabel("Name", { exact: true })).toHaveValue("Pending creature");
    await expect(add.getByLabel("XP per creature")).toHaveValue("250"); await expect(add.getByLabel("Quantity")).toHaveValue("4");
    await expect(main.getByRole("button", { name: "Save encounter", exact: true })).toBeDisabled();
    expect((await pool.query("SELECT title, notes FROM encounter WHERE id=$1", [id])).rows[0]).toEqual({ title: "Crossing", notes: null });
    await creature.getByLabel("Name", { exact: true }).fill("   ");
    await creature.getByLabel("XP per creature").fill("300");
    await creature.getByRole("button", { name: "Save creature", exact: true }).click();
    await expect(creature.getByRole("alert")).toBeVisible(); await expect(creature.getByLabel("XP per creature")).toHaveValue("300");
    await creature.getByLabel("Name", { exact: true }).fill("Pending guard");
    await recoverPlanning(main, 3);
    await main.getByRole("button", { name: "Save encounter", exact: true }).click();
    await expect(main.locator('input[name="expectedRevision"]')).toHaveValue("4");
    await expect(creature.getByLabel("Name", { exact: true })).toHaveValue("Pending guard");
    await expect(creature.locator('input[name="expectedRevision"]')).toHaveValue("3");
    await recoverPlanning(creature, 4);
    await other.goto(page.url());
    await other.locator("#encounter-notes").fill("Remote accepted plan");
    await other.getByRole("button", { name: "Save encounter", exact: true }).click();
    await expect(editor(other, "#encounter-title").locator('input[name="expectedRevision"]')).toHaveValue("5");
    await creature.getByRole("button", { name: "Save creature", exact: true }).click();
    await expect(creature.getByRole("alert")).toContainText("draft is retained");
    await expect(creature.getByLabel("Name", { exact: true })).toHaveValue("Pending guard");
    await recoverPlanning(creature, 5);
    await creature.getByRole("button", { name: "Save creature", exact: true }).click();
    await expect(creature.locator('input[name="expectedRevision"]')).toHaveValue("6");
    expect((await pool.query("SELECT name, xp, quantity FROM encounter_srd_521_creature WHERE encounter_id=$1", [id])).rows[0])
      .toEqual({ name: "Pending guard", xp: 300, quantity: 2 });
    await main.getByRole("button", { name: "View persisted values for this section", exact: true }).click();
    await main.getByRole("button", { name: "Load persisted values (discard this draft)", exact: true }).click();
    await expect(main.getByLabel("Preparation notes")).toHaveValue("Remote accepted plan");
    await expect(add.getByLabel("Name", { exact: true })).toHaveValue("Pending creature");
  } finally { await other.close(); await pool.end(); }
});
